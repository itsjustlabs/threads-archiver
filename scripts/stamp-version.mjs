#!/usr/bin/env node
/**
 * Writes threads-archiver/shared/version.js from manifest.json + the current
 * git commit, so the extension can display which build is loaded.
 *
 * Run manually (`node scripts/stamp-version.mjs`) or via the pre-commit hook.
 * Note: a commit can't contain its own hash, so when run from pre-commit the
 * stamped commit is HEAD at commit time (the parent of the commit being made).
 * For an exact match to what you're running, run it after checkout, before
 * loading the unpacked extension.
 */
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ext  = path.join(root, 'threads-archiver');

const manifest = JSON.parse(fs.readFileSync(path.join(ext, 'manifest.json'), 'utf8'));
const git = cmd => { try { return execSync(cmd, { cwd: root }).toString().trim(); } catch { return ''; } };
const commit = git('git rev-parse --short HEAD') || 'unknown';
const date   = new Date().toISOString().slice(0, 10);

const out =
`// AUTO-GENERATED by scripts/stamp-version.mjs — do not edit by hand.
export const BUILD = ${JSON.stringify({ version: manifest.version, commit, date }, null, 2)};
`;
fs.writeFileSync(path.join(ext, 'shared', 'version.js'), out);
console.log(`stamped version.js → v${manifest.version} · ${commit} · ${date}`);
